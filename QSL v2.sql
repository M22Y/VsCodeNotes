WITH PERIOD_FILTER AS (
	SELECT COD_PERIODO
	FROM SCENARIO_PERIODO
	WHERE COD_RACCOLTA='#PROCESS#' AND FLAG_BLOCCATO=0
	AND COD_SCENARIO=(SELECT COD_SCENARIO FROM SCENARIO_PERIODO WHERE COD_RACCOLTA ='#PROCESS#' ORDER BY COD_SCENARIO LIMIT 1)
),
CombinedTables AS (  
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"01").code, $Scenario.attribute5.code, "01")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"02").code, $Scenario.attribute5.code, "02")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"03").code, $Scenario.attribute5.code, "03")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"04").code, $Scenario.attribute5.code, "04")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"05").code, $Scenario.attribute5.code, "05")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"06").code, $Scenario.attribute5.code, "06")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"07").code, $Scenario.attribute5.code, "07")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"08").code, $Scenario.attribute5.code, "08")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"09").code, $Scenario.attribute5.code, "09")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"10").code, $Scenario.attribute5.code, "10")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"11").code, $Scenario.attribute5.code, "11")}
	UNION ALL
	SELECT * FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"12").code, $Scenario.attribute5.code, "12")}
),
MONTHLY AS (
	SELECT 
		SCENARIO,
		PERIOD,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN,
		SUM(AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables
	WHERE 
		PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		AND SCENARIO IN  (SELECT ATTRIBUTO5 FROM SCENARIO WHERE COD_SCENARIO= '#SCENARIOS#' LIMIT 1)
	GROUP BY 
		SCENARIO,
		PERIOD,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN     
	HAVING 
		SUM(AMOUNT)<>0
),
TOT AS (
	SELECT 
		SCENARIO,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN,
		SUM(AMOUNT) AS M_TOT
	FROM 
		CombinedTables
	WHERE 
		PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		AND SCENARIO IN  (SELECT ATTRIBUTO5 FROM SCENARIO WHERE COD_SCENARIO= '#SCENARIOS#' LIMIT 1)
	GROUP BY 
		SCENARIO,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN   
	HAVING 
		SUM(AMOUNT)<>0
)
SELECT  
	'#PROCESS#' AS SCENARIO, 
	MONTHLY.SCENARIO AS HIST_SCENARIO,
	MONTHLY.PERIOD,
	MONTHLY.ACCOUNT,
	MONTHLY.ENTITY,
	MONTHLY.CATEGORY,
	MONTHLY.DIVISION,
	MONTHLY.CUSTOMER,
	MONTHLY.PRODUCT,
	MONTHLY.RSRCE,
    MONTHLY.OPE_TYPE,
	MONTHLY.TEXT_ORIGIN,
	SUM(MONTHLY.M_AMOUNT / TOT.M_TOT) AS PERC_DRIVER
FROM
	MONTHLY
LEFT JOIN 
	TOT
ON 
	MONTHLY.SCENARIO = TOT.SCENARIO
	AND MONTHLY.ACCOUNT = TOT.ACCOUNT
	AND MONTHLY.ENTITY = TOT.ENTITY
	AND MONTHLY.CATEGORY = TOT.CATEGORY
	AND MONTHLY.DIVISION = TOT.DIVISION
	AND MONTHLY.CUSTOMER = TOT.CUSTOMER
	AND MONTHLY.PRODUCT = TOT.PRODUCT
	AND MONTHLY.RSRCE = TOT.RSRCE
    AND MONTHLY.OPE_TYPE = TOT.OPE_TYPE


WHERE 
	MONTHLY.SCENARIO IN  (SELECT ATTRIBUTO5 FROM SCENARIO WHERE COD_SCENARIO= '#SCENARIOS#' LIMIT 1)
GROUP BY 
	MONTHLY.SCENARIO,
	MONTHLY.PERIOD,
	MONTHLY.ACCOUNT,
	MONTHLY.ENTITY,
	MONTHLY.CATEGORY,
	MONTHLY.DIVISION,
	MONTHLY.CUSTOMER,
	MONTHLY.PRODUCT,
	MONTHLY.RSRCE,
    MONTHLY.OPE_TYPE,
	MONTHLY.TEXT_ORIGIN

