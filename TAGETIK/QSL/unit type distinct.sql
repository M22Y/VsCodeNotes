SELECT DISTINCT
    T.SCENARIO AS SCENARIO,
    T.PERIOD AS PERIOD,
    LEFT(T.RESOURCES, 6) || '_Q' AS ACCOUNT,
    T.ENTITY AS ENTITY,
    T.DIVISION AS DIVISION,
    T.CUSTOMER AS CUSTOMER,
    T.PRODUCT AS PRODUCT,
    T.S1_BDG_UNIT_TYPE AS UNIT_TYPE
FROM ${DATASETPARTITION("004", "000005", PROCESS($Scenario.code,"12").code, $Scenario.code,,,,"(SELECT NULL AS SCENARIO, NULL AS PERIOD,NULL AS ACCOUNT, NULL AS ENTITY, NULL AS DIVISION, NULL AS CUSTOMER, NULL AS PRODUCT, NULL AS RESOURCES, NULL AS S1_BDG_UNIT_TYPE)")} AS T
WHERE T.S1_BDG_UNIT_TYPE IS NOT NULL
AND T.RESOURCES IN ('400110A0000', '400120A0000')