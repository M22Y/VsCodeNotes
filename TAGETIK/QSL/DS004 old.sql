SELECT DISTINCT
    T.SCENARIO AS SCENARIO,
    T.ENTITY AS ENTITY,
    T.DIVISION AS DIVISION


FROM ${DATASETPARTITION("006", "000007", PROCESS($Scenario.code,"01").code, $Scenario.code, "01",,,"(SELECT NULL AS SCENARIO, NULL AS PERIOD, NULL AS ACCOUNT, NULL AS ENTITY, NULL AS DIVISION, NULL AS CUSTOMER, NULL AS PRODUCT, 0 AS AMOUNT, NULL AS TEXT_ORIGIN)")} AS T


WHERE 
    T.SCENARIO=${$Scenario.code}
    AND T.AMOUNT <> 0
    AND T.TEXT_ORIGIN = 'AW006_RV_AMOUNT'

