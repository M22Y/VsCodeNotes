WITH FilteredConditions AS (
  SELECT  B.COD,  B.DESC0,  CONTO.COD_CONTO, CONTO.DESC_CONTO0
  FROM CONTO
  JOIN ED_CO_00006 AS B ON (CONTO.COD_CONTO LIKE '%' || B.COD || '%'
    OR (CONTO.COD_CONTO LIKE 'DF_NDEBT_IGM_BD_%' AND B.COD = 'DEBT_PUB')
    OR (CONTO.COD_CONTO LIKE 'DF_NDEBT_LFC_BD%' AND B.COD = 'DEBT_PUB')
    OR (CONTO.COD_CONTO LIKE 'DF_NDEBT_PFC_BD_%' AND B.COD = 'DEBT_PUB')
    OR (CONTO.COD_CONTO LIKE 'DF_NSH_1STPREF_%' AND B.COD = 'SH_1STPREF'))
)
SELECT  CONTO.COD AS NOTE_COD,
  CONTO.DESC0 AS NOTE_DESC,
  CONTO.COD_CONTO AS ACC_COD,
  CONTO.DESC_CONTO0 AS ACC_DESC,
  CONTO2.COD_CONTO AS ACC_COD2,
CONTO2.DESC_CONTO0 AS ACC_DESC2

FROM FilteredConditions CONTO
JOIN FilteredConditions CONTO2 ON CONTO2.COD_CONTO LIKE '%' || CONTO.COD || '%'

WHERE CONTO.COD_CONTO LIKE 'DF%' AND CONTO.COD_CONTO NOT LIKE 'FW%'
AND CONTO2.COD_CONTO LIKE 'DF%' AND CONTO2.COD_CONTO NOT LIKE 'FW%'
ORDER BY CONTO.COD, CONTO.COD_CONTO, CONTO2.COD_CONTO ASC