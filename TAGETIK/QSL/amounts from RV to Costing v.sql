SELECT 
    T.SCENARIO AS SCENARIO,
    T.PERIOD AS PERIOD,
    LEFT(T.RSRCE, 6) AS ACCOUNT,
    T.ENTITY AS ENTITY,
    'CO_RV_AMOUNT' AS CATEGORY,
    T.DIVISION AS DIVISION,
    T.CUSTOMER AS CUSTOMER,
    T.PRODUCT AS PRODUCT,
    SUM(T.AMOUNT) AS AMOUNT,
    T.TEXT_ORIGIN AS TEXT_ORIGIN

FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.code,"01").code, $Scenario.code, "01",,,"(SELECT NULL AS SCENARIO, NULL AS PERIOD, NULL AS ACCOUNT, NULL AS ENTITY, NULL AS CATEGORY, NULL AS DIVISION, NULL AS CUSTOMER, NULL AS PRODUCT, NULL AS RSRCE, 0 AS AMOUNT, NULL AS TEXT_ORIGIN)")} AS T
-- FROM  AW_004_000003_000001 T

WHERE 
    T.CATEGORY IN ('RV_AMOUNT', 'RV_ADJ')
    AND T.ACCOUNT='RV_REVENUES'
    AND T.AMOUNT <> 0
    AND T.TEXT_ORIGIN = 'AW004_INPUT_DE060'
GROUP BY 
    T.SCENARIO, 
    T.PERIOD, 
    LEFT(T.RSRCE, 6),
    T.ENTITY, 
    T.DIVISION, 
    T.CUSTOMER, 
    T.PRODUCT,
    T.TEXT_ORIGIN
