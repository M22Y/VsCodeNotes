WITH PERIOD_FILTER AS (
	SELECT COD_PERIODO
	FROM SCENARIO_PERIODO
	WHERE COD_RACCOLTA='2025BDG' AND FLAG_BLOCCATO=0
	AND COD_SCENARIO=(SELECT COD_SCENARIO FROM SCENARIO_PERIODO WHERE COD_RACCOLTA ='2025BDG' ORDER BY COD_SCENARIO LIMIT 1)
), CombinedTables AS (
	SELECT * FROM AW_004_000003_000003
	UNION ALL SELECT * FROM AW_004_000003_000004 
	UNION ALL SELECT * FROM AW_004_000003_000005 
	UNION ALL SELECT * FROM AW_004_000003_000006 
	UNION ALL SELECT * FROM AW_004_000003_000007 
	UNION ALL SELECT * FROM AW_004_000003_000008 
	UNION ALL SELECT * FROM AW_004_000003_000009 
	UNION ALL SELECT * FROM AW_004_000003_000010 
	UNION ALL SELECT * FROM AW_004_000003_000011
	UNION ALL SELECT * FROM AW_004_000003_000013
	UNION ALL SELECT * FROM AW_004_000003_000014 
	UNION ALL SELECT * FROM AW_004_000003_000015 

),MONTHLY AS (
	SELECT 
		SCENARIO,
		PERIOD,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN,
		SUM(AMOUNT) AS M_AMOUNT
	FROM 
		 CombinedTables AS CT
	WHERE 
		SCENARIO='2024ACT'
		AND PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
	GROUP BY 
		SCENARIO,
		PERIOD,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN     
	HAVING 
		SUM(AMOUNT)<>0
), TOT AS (
	SELECT 
		SCENARIO,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN,
		SUM(AMOUNT) AS M_TOT
	FROM 
		CombinedTables AS CT
	WHERE 
		SCENARIO='2024ACT'
		AND PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
	GROUP BY 
		SCENARIO,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN   
	HAVING 
		SUM(AMOUNT)<>0
) 

SELECT  
	'2025BDG' AS SCENARIO, 
	MONTHLY.SCENARIO AS HIST_SCENARIO,
	MONTHLY.PERIOD,
	MONTHLY.ACCOUNT,
	MONTHLY.ENTITY,
	MONTHLY.CATEGORY,
	MONTHLY.DIVISION,
	MONTHLY.CUSTOMER,
	MONTHLY.PRODUCT,
	MONTHLY.RSRCE,
    MONTHLY.OPE_TYPE,
	MONTHLY.TEXT_ORIGIN,
	SUM(MONTHLY.M_AMOUNT) AS MONTHLY_AMOUNT,
	SUM(MONTHLY.M_AMOUNT / TOT.M_TOT) AS PERC_DRIVER
FROM
	 MONTHLY
JOIN 
	TOT
ON 
	MONTHLY.SCENARIO = TOT.SCENARIO
	AND MONTHLY.ACCOUNT = TOT.ACCOUNT
	AND MONTHLY.ENTITY = TOT.ENTITY
	AND MONTHLY.CATEGORY = TOT.CATEGORY
	AND MONTHLY.DIVISION = TOT.DIVISION
	AND MONTHLY.CUSTOMER = TOT.CUSTOMER
	AND MONTHLY.PRODUCT = TOT.PRODUCT
	AND MONTHLY.RSRCE = TOT.RSRCE
    AND MONTHLY.OPE_TYPE = TOT.OPE_TYPE
WHERE 
	MONTHLY.SCENARIO='2024ACT'
GROUP BY 
	MONTHLY.SCENARIO,
	MONTHLY.PERIOD,
	MONTHLY.ACCOUNT,
	MONTHLY.ENTITY,
	MONTHLY.CATEGORY,
	MONTHLY.DIVISION,
	MONTHLY.CUSTOMER,
	MONTHLY.PRODUCT,
	MONTHLY.RSRCE,
    MONTHLY.OPE_TYPE,
	MONTHLY.TEXT_ORIGIN

