WITH PERIOD_FILTER AS (
	SELECT COD_PERIODO
	FROM SCENARIO_PERIODO
	WHERE COD_RACCOLTA='2025BDG' AND FLAG_BLOCCATO=0
	AND COD_SCENARIO=(SELECT COD_SCENARIO FROM SCENARIO_PERIODO WHERE COD_RACCOLTA ='2025BDG' ORDER BY COD_SCENARIO LIMIT 1)
),
CombinedTables AS (  
	SELECT SCENARIO,PERIOD,ACCOUNT,ENTITY,CATEGORY,DIVISION,CUSTOMER,PRODUCT,RSRCE,OPE_TYPE,TEXT_ORIGIN,AMOUNT 
	FROM AW_004_000003_000003 AS T03
	UNION ALL
	SELECT SCENARIO,PERIOD,ACCOUNT,ENTITY,CATEGORY,DIVISION,CUSTOMER,PRODUCT,RSRCE,OPE_TYPE,TEXT_ORIGIN,AMOUNT 
	FROM AW_004_000003_000012 AS T02
	UNION ALL
	SELECT SCENARIO,PERIOD,ACCOUNT,ENTITY,CATEGORY,DIVISION,CUSTOMER,PRODUCT,RSRCE,OPE_TYPE,TEXT_ORIGIN,AMOUNT 
	FROM AW_004_000003_000013 AS T03
	UNION ALL
	SELECT SCENARIO,PERIOD,ACCOUNT,ENTITY,CATEGORY,DIVISION,CUSTOMER,PRODUCT,RSRCE,OPE_TYPE,TEXT_ORIGIN,AMOUNT 
	FROM AW_004_000003_000014 AS T04
),
DENOMINATOR AS (
	SELECT 
		CT.SCENARIO,
		CT.ACCOUNT,
		CT.ENTITY,
		CT.CATEGORY,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT,
        CT.OPE_TYPE,
		SUM(CT.AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables AS CT
	WHERE 
		CT.PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		AND CT.SCENARIO IN  ('2024ACT')
        AND CT.RSRCE IN (SELECT COD FROM  ED_RESOURCE_GERARCHIA_FLAT WHERE COD_GERARCHIA='999' AND COD_ELEGER7 like '%STV_TLG%')
	GROUP BY 
		CT.SCENARIO,
		CT.ACCOUNT,
		CT.ENTITY,
		CT.CATEGORY,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT,
        CT.OPE_TYPE
	HAVING 
		SUM(CT.AMOUNT)<>0
),
NUMERATOR AS (
	SELECT 
		CT.SCENARIO,
		CT.ACCOUNT,
		CT.ENTITY,
		CT.CATEGORY,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT,
		CT.RSRCE,
        CT.OPE_TYPE,
		SUM(CT.AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables AS CT
	WHERE 
		CT.PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		AND CT.SCENARIO IN  ('2024ACT')
        AND CT.RSRCE NOT IN (SELECT COD FROM  ED_RESOURCE_GERARCHIA_FLAT WHERE COD_GERARCHIA='999')
	GROUP BY 
		CT.SCENARIO,
		CT.ACCOUNT,
		CT.ENTITY,
		CT.CATEGORY,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT,
		CT.RSRCE,
        CT.OPE_TYPE 
	HAVING 
		SUM(CT.AMOUNT)<>0
)
SELECT  
	'2025BDG' AS SCENARIO, 
	NUMERATOR.SCENARIO AS HIST_SCENARIO,
	NUMERATOR.ACCOUNT,
	NUMERATOR.ENTITY,
	NUMERATOR.CATEGORY,
	NUMERATOR.DIVISION,
	NUMERATOR.CUSTOMER,
	NUMERATOR.PRODUCT,
	NUMERATOR.RSRCE,
    NUMERATOR.OPE_TYPE,
	SUM(NUMERATOR.M_AMOUNT / DENOMINATOR.M_AMOUNT) AS VALUE_PERCENTAGE
FROM
	NUMERATOR
LEFT JOIN 
	DENOMINATOR
ON 
	NUMERATOR.SCENARIO = DENOMINATOR.SCENARIO
	AND NUMERATOR.ACCOUNT = DENOMINATOR.ACCOUNT
	AND NUMERATOR.ENTITY = DENOMINATOR.ENTITY
	AND NUMERATOR.CATEGORY = DENOMINATOR.CATEGORY
	AND NUMERATOR.DIVISION = DENOMINATOR.DIVISION
	AND NUMERATOR.CUSTOMER = DENOMINATOR.CUSTOMER
	AND NUMERATOR.PRODUCT = DENOMINATOR.PRODUCT
    AND NUMERATOR.OPE_TYPE = DENOMINATOR.OPE_TYPE

WHERE 
	NUMERATOR.SCENARIO IN  ('2024ACT')
	AND NUMERATOR.CATEGORY = 'RV_AMOUNT'
GROUP BY 
	NUMERATOR.SCENARIO,
	NUMERATOR.ACCOUNT,
	NUMERATOR.ENTITY,
	NUMERATOR.CATEGORY,
	NUMERATOR.DIVISION,
	NUMERATOR.CUSTOMER,
	NUMERATOR.PRODUCT,
	NUMERATOR.RSRCE,
    NUMERATOR.OPE_TYPE
HAVING 
	SUM(NUMERATOR.M_AMOUNT / DENOMINATOR.M_AMOUNT)<>0
