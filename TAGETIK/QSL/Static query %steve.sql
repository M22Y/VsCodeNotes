WITH PERIOD_FILTER AS (
	SELECT COD_PERIODO
	FROM SCENARIO_PERIODO
	WHERE COD_RACCOLTA='2025BDG' AND FLAG_BLOCCATO=0
	AND COD_SCENARIO=(SELECT COD_SCENARIO FROM SCENARIO_PERIODO WHERE COD_RACCOLTA ='2025BDG' ORDER BY COD_SCENARIO LIMIT 1)
),
CombinedTables AS (  
	SELECT SCENARIO,PERIOD,ACCOUNT,ENTITY,CATEGORY,DIVISION,CUSTOMER,PRODUCT,RSRCE,OPE_TYPE,TEXT_ORIGIN,AMOUNT 
	FROM AW_004_000003_000003
),
DENOMINATOR AS (
	SELECT 
		SCENARIO,
		PERIOD,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN,
		SUM(AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables
	WHERE 
		PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		AND SCENARIO IN  (SELECT ATTRIBUTO5 FROM SCENARIO WHERE COD_SCENARIO= '2025BDG' LIMIT 1)
        AND RSRCE IN (SELECT COD FROM  ED_RESOURCE_GERARCHIA_FLAT WHERE COD_GERARCHIA='999' AND COD_ELEGER6 like '%STV%')
	GROUP BY 
		SCENARIO,
		PERIOD,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN     
	HAVING 
		SUM(AMOUNT)<>0
),
NUMERATOR AS (
	SELECT 
		SCENARIO,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN,
		SUM(AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables
	WHERE 
		PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		AND SCENARIO IN  (SELECT ATTRIBUTO5 FROM SCENARIO WHERE COD_SCENARIO= '2025BDG' LIMIT 1)
        AND RSRCE NOT IN (SELECT COD FROM  ED_RESOURCE_GERARCHIA_FLAT WHERE COD_GERARCHIA<>'999')
	GROUP BY 
		SCENARIO,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN   
	HAVING 
		SUM(AMOUNT)<>0
)
SELECT  
	'2025BDG' AS SCENARIO, 
	NUMERATOR.SCENARIO AS HIST_SCENARIO,
	NUMERATOR.PERIOD,
	NUMERATOR.ACCOUNT,
	NUMERATOR.ENTITY,
	NUMERATOR.CATEGORY,
	NUMERATOR.DIVISION,
	NUMERATOR.CUSTOMER,
	NUMERATOR.PRODUCT,
	NUMERATOR.RSRCE,
    NUMERATOR.OPE_TYPE,
	NUMERATOR.TEXT_ORIGIN,
	SUM(NUMERATOR.M_AMOUNT / DENOMINATOR.M_AMOUNT) AS VALUE_%
FROM
	NUMERATOR
LEFT JOIN 
	DENOMINATOR
ON 
	NUMERATOR.SCENARIO = DENOMINATOR.SCENARIO
	AND NUMERATOR.ACCOUNT = DENOMINATOR.ACCOUNT
	AND NUMERATOR.ENTITY = TDENOMINATOROT.ENTITY
	AND NUMERATOR.CATEGORY = DENOMINATOR.CATEGORY
	AND NUMERATOR.DIVISION = DENOMINATOR.DIVISION
	AND NUMERATOR.CUSTOMER = DENOMINATOR.CUSTOMER
	AND NUMERATOR.PRODUCT = DENOMINATOR.PRODUCT
	AND NUMERATOR.RSRCE = DENOMINATOR.RSRCE
    AND NUMERATOR.OPE_TYPE = DENOMINATOR.OPE_TYPE

WHERE 
	NUMERATOR.SCENARIO IN  (SELECT ATTRIBUTO5 FROM SCENARIO WHERE COD_SCENARIO= '2025BDG' LIMIT 1)
	AND NUMERATOR.CATEGORY = 'RV_AMOUNT'
GROUP BY 
	NUMERATOR.SCENARIO,
	NUMERATOR.PERIOD,
	NUMERATOR.ACCOUNT,
	NUMERATOR.ENTITY,
	NUMERATOR.CATEGORY,
	NUMERATOR.DIVISION,
	NUMERATOR.CUSTOMER,
	NUMERATOR.PRODUCT,
	NUMERATOR.RSRCE,
    NUMERATOR.OPE_TYPE,
	NUMERATOR.TEXT_ORIGIN

