Special method : Load to Financial workspace
Description : Load data from a partition to Dati_Saldi_Lordi for a specific Entity/Division contexte
Updated : Youssef. M - 23-03-2026

*/


DELETE FROM DATI_SALDI_LORDI
WHERE COD_SCENARIO = ${$Scenario.code}
AND COD_DEST2 IN (SELECT DISTINCT DIVISION FROM #TARGET_PARTITION#)
AND COD_AZIENDA IN (SELECT DISTINCT ENTITY FROM #TARGET_PARTITION#)
AND PROVENIENZA = 'QDL';
 
WITH PERIODS AS (
  SELECT '01' AS COD_PERIODO
  UNION ALL SELECT '02'
  UNION ALL SELECT '03'
  UNION ALL SELECT '04'
  UNION ALL SELECT '05'
  UNION ALL SELECT '06'
  UNION ALL SELECT '07'
  UNION ALL SELECT '08'
  UNION ALL SELECT '09'
  UNION ALL SELECT '10'
  UNION ALL SELECT '11'
  UNION ALL SELECT '12'
),
SOURCE_MTD AS (
  SELECT
    SCENARIO,
    PERIOD AS SOURCE_PERIOD,
    ENTITY,
    ACCOUNT,
    DIVISION,
    PRODUCT,
    CUSTOMER,
    CATEGORY,
    CURRENCY,
    SUM(VALUE_DOLLARS) AS VALUE_MTD
  FROM #TARGET_PARTITION#
  GROUP BY
    SCENARIO,
    PERIOD,
    ENTITY,
    ACCOUNT,
    DIVISION,
    PRODUCT,
    CUSTOMER,
    CATEGORY,
    CURRENCY
),
BASE_COMBINATIONS AS (
  SELECT DISTINCT
    SCENARIO,
    ENTITY,
    ACCOUNT,
    DIVISION,
    PRODUCT,
    CUSTOMER,
    CATEGORY,
    CURRENCY
  FROM SOURCE_MTD
),
EXPANDED AS (
  SELECT
    B.SCENARIO,
    P.COD_PERIODO,
    B.ENTITY,
    B.ACCOUNT,
    B.DIVISION,
    B.PRODUCT,
    B.CUSTOMER,
    B.CATEGORY,
    B.CURRENCY
  FROM BASE_COMBINATIONS B
  CROSS JOIN PERIODS P
),
YTD_DATA AS (
  SELECT
    E.SCENARIO,
    E.COD_PERIODO,
    E.ENTITY,
    E.ACCOUNT,
    E.DIVISION,
    E.PRODUCT,
    E.CUSTOMER,
    E.CATEGORY,
    E.CURRENCY,
    SUM(COALESCE(S.VALUE_MTD, 0)) OVER (
      PARTITION BY E.SCENARIO, E.ENTITY, E.CATEGORY, E.DIVISION, E.ACCOUNT, E.CURRENCY, E.CUSTOMER, E.PRODUCT
      ORDER BY E.COD_PERIODO
      ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS VALUE_YTD
  FROM EXPANDED E
  LEFT JOIN SOURCE_MTD S
    ON E.SCENARIO IS NOT DISTINCT FROM S.SCENARIO
   AND E.COD_PERIODO = S.SOURCE_PERIOD
   AND E.ENTITY IS NOT DISTINCT FROM S.ENTITY
   AND E.ACCOUNT IS NOT DISTINCT FROM S.ACCOUNT
   AND E.DIVISION IS NOT DISTINCT FROM S.DIVISION
   AND E.PRODUCT IS NOT DISTINCT FROM S.PRODUCT
   AND E.CUSTOMER IS NOT DISTINCT FROM S.CUSTOMER
   AND E.CATEGORY IS NOT DISTINCT FROM S.CATEGORY
   AND E.CURRENCY IS NOT DISTINCT FROM S.CURRENCY
)
INSERT INTO DATI_SALDI_LORDI (
  OID_DATI_SALDI_LORDI,
  COD_SCENARIO,
  COD_PERIODO,
  COD_AZIENDA,
  COD_CONTO,
  COD_DEST1,
  COD_DEST2,
  COD_DEST3,
  COD_DEST4,
  COD_DEST5,
  COD_CATEGORIA,
  IMPORTO,
  COD_VALUTA,
  IMPORTO_VALUTA_ORIGINARIA,
  COD_VALUTA_ORIGINARIA,
  PROVENIENZA,
  USERUPD,
  DATEUPD
)
SELECT
  uuid_generate_v1()                       AS OID_DATI_SALDI_LORDI,
  SCENARIO                                 AS COD_SCENARIO,
  COD_PERIODO                              AS COD_PERIODO,
  ENTITY                                   AS COD_AZIENDA,
  ACCOUNT                                  AS COD_CONTO,
  'NA'                                     AS COD_DEST1,
  DIVISION                                 AS COD_DEST2,
  PRODUCT                                  AS COD_DEST3,
  CUSTOMER                                 AS COD_DEST4,
  'NA'                                     AS COD_DEST5,
  CATEGORY                                 AS COD_CATEGORIA,
  VALUE_YTD                                AS IMPORTO,
  CURRENCY                                 AS COD_VALUTA,
  VALUE_YTD                                AS IMPORTO_VALUTA_ORIGINARIA,
  CURRENCY                                 AS COD_VALUTA_ORIGINARIA,
  'QDL'                                    AS PROVENIENZA,
  '#USER#'                                 AS USERUPD,
  NOW()                                    AS DATEUPD
FROM YTD_DATA
WHERE VALUE_YTD <> 0;