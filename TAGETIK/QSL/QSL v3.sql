		SCENARIO,
		PERIOD,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN,
		SUM(AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables
	WHERE 
		PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		AND SCENARIO IN  (SELECT ATTRIBUTO5 FROM SCENARIO WHERE COD_SCENARIO= '#SCENARIOS#' LIMIT 1)
	GROUP BY 
		SCENARIO,
		PERIOD,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        OPE_TYPE,
		TEXT_ORIGIN     
	HAVING 
		SUM(AMOUNT)<>0
),
