
	
	WITH PERIOD_FILTER AS (
	SELECT COD_PERIODO
	FROM SCENARIO_PERIODO
	WHERE COD_RACCOLTA='2025BDG' AND FLAG_BLOCCATO=0
	AND COD_SCENARIO=(SELECT COD_SCENARIO FROM SCENARIO_PERIODO WHERE COD_RACCOLTA ='2025BDG' ORDER BY COD_SCENARIO LIMIT 1)
),
CombinedTables AS (  
	SELECT SCENARIO,PERIOD,ACCOUNT,ENTITY,CATEGORY,DIVISION,CUSTOMER,PRODUCT,RSRCE,OPE_TYPE,TEXT_ORIGIN,AMOUNT 
	FROM AW_004_000003_000039 AS T1
	

),
DENOMINATOR AS (
	SELECT 
		CT.SCENARIO,
		CT.ENTITY,
		CT.CATEGORY,
		CT.ACCOUNT,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT,
		SUM(CT.AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables AS CT
	WHERE 
		CT.PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		        AND CT.ACCOUNT = 'RV_REVENUES'
		AND CT.SCENARIO IN  (SELECT COD_SCENARIO_RIF1 FROM SCENARIO WHERE COD_SCENARIO= '2025BDG' LIMIT 1)
        AND CT.RSRCE IN (SELECT COD FROM  ED_RESOURCE_GERARCHIA_FLAT WHERE COD_GERARCHIA='999' AND COD_ELEGER6 like '%TLG%')
	GROUP BY 
		CT.SCENARIO,
		CT.ENTITY,
		CT.CATEGORY,
		CT.ACCOUNT,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT
	HAVING 
		SUM(CT.AMOUNT)<>0
),
NUMERATOR AS (
	SELECT 
		CT.SCENARIO,
		CT.ENTITY,
		CT.CATEGORY,
		CT.ACCOUNT,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT,
		CT.RSRCE,
		SUM(CT.AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables AS CT
	WHERE 
		CT.PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		        AND CT.ACCOUNT = 'RV_REVENUES'
		AND CT.SCENARIO IN  (SELECT COD_SCENARIO_RIF1 FROM SCENARIO WHERE COD_SCENARIO= '2025BDG' LIMIT 1)
        AND CT.RSRCE NOT IN (SELECT COD FROM  ED_RESOURCE_GERARCHIA_FLAT WHERE COD_GERARCHIA='999')
	GROUP BY 
		CT.SCENARIO,
		CT.ENTITY,
		CT.CATEGORY,
		CT.ACCOUNT,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT,
		CT.RSRCE
	HAVING 
		SUM(CT.AMOUNT)<>0
)
SELECT  
	'2025BDG' AS SCENARIO, 
	NUMERATOR.SCENARIO AS HIST_SCENARIO,
	NUMERATOR.ENTITY,
	NUMERATOR.CATEGORY,
	NUMERATOR.ACCOUNT,
	NUMERATOR.DIVISION,
	NUMERATOR.CUSTOMER,
	NUMERATOR.PRODUCT,
	NUMERATOR.RSRCE,
	SUM(NUMERATOR.M_AMOUNT / DENOMINATOR.M_AMOUNT) AS VALUE_PERCENTAGE
FROM
	NUMERATOR
LEFT JOIN 
	DENOMINATOR
ON 
	NUMERATOR.SCENARIO = DENOMINATOR.SCENARIO
	AND NUMERATOR.ENTITY = DENOMINATOR.ENTITY
	AND NUMERATOR.ACCOUNT = DENOMINATOR.ACCOUNT
	AND NUMERATOR.CATEGORY = DENOMINATOR.CATEGORY
	AND NUMERATOR.DIVISION = DENOMINATOR.DIVISION
	AND NUMERATOR.CUSTOMER = DENOMINATOR.CUSTOMER
	AND NUMERATOR.PRODUCT = DENOMINATOR.PRODUCT


WHERE 
	NUMERATOR.SCENARIO IN  (SELECT COD_SCENARIO_RIF1 FROM SCENARIO WHERE COD_SCENARIO= '2025BDG' LIMIT 1)
	AND NUMERATOR.CATEGORY = 'RV_AMOUNT'
GROUP BY 
	NUMERATOR.SCENARIO,
	NUMERATOR.ENTITY,
	NUMERATOR.CATEGORY,
	NUMERATOR.ACCOUNT,
	NUMERATOR.DIVISION,
	NUMERATOR.CUSTOMER,
	NUMERATOR.PRODUCT,
	NUMERATOR.RSRCE
HAVING 
	SUM(NUMERATOR.M_AMOUNT / DENOMINATOR.M_AMOUNT)<>0


