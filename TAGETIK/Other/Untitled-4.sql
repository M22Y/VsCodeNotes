
WITH TECH_MIN_UNLOCKED_PERIOD AS (SELECT CAST(MIN(COD_PERIODO) AS DECIMAL) AS MIN_PERIOD
FROM SCENARIO_PERIODO
WHERE COD_RACCOLTA=${PROCESS($Scenario.code, "01").Code} AND FLAG_BLOCCATO=0
AND COD_SCENARIO=(SELECT COD_SCENARIO FROM SCENARIO_PERIODO WHERE COD_RACCOLTA =${PROCESS($Scenario.code, "01").Code} ORDER BY COD_SCENARIO LIMIT 1)
)
SELECT

(CASE 
WHEN 1 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P01,
(CASE 
WHEN 2 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P02,
(CASE 
WHEN 3 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P03,
(CASE 
WHEN 4 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P04,
(CASE 
WHEN 5 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P05,
(CASE 
WHEN 6 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P06,
(CASE 
WHEN 7 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P07,
(CASE 
WHEN 8 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P08,
(CASE 
WHEN 9 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P09,
(CASE 
WHEN 10 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P10,
(CASE 
WHEN 11 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P11,
(CASE 
WHEN 12 >= TECH_MIN_UNLOCKED_PERIOD.MIN_PERIOD THEN 'TRUE'
ELSE 'FALSE'
END) AS P12

FROM TECH_MIN_UNLOCKED_PERIOD













