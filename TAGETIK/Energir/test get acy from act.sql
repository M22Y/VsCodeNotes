SELECT *
FROM AW_002_CYT001_000264 SOURCE
WHERE SOURCE.TGK_COD_AZIENDA = 'A1401'
	AND (
		TGK_COD_AZIENDA IN ('A1401')
		AND SRC_COD_SCENARIO = (
			SELECT MAX(
					CASE
						WHEN CAST('12' AS INT) < 4 THEN CONCAT(
							CAST(CAST(LEFT('2025ACT', 4) AS INT) - 1 AS VARCHAR),
							'ACY'
						)
						ELSE CONCAT(
							CAST(CAST(LEFT('2025ACT', 4) AS INT) AS VARCHAR),
							'ACY'
						)
					END
				) AS COD_SCENARIO
			FROM SCENARIO
		)
		AND SRC_COD_PERIODO = (
			SELECT MAX(MAP.SRC_COD_PERIODO)
			FROM AW_002_MAP012_000001 MAP
			WHERE (
					MAP.TGK_COD_AZIENDA IN ('A1401')
					OR MAP.TGK_COD_AZIENDA = '%'
				)
				AND MAP.TGK_COD_PERIODO = '12'
		)
		AND PROVENIENZA = 'DTP_ELAB'
	)