SELECT 
D.SCENARIO SCENARIO,
D.SCEN_TYPE SCEN_CONSO,
D.PERIOD PERIOD,
D.ANL_ENTITY SOURCE_ENTITY_C,
A.DESC0 SOURCE_ENTITY_DESC,
D.ACCOUNT Account_Code,
C.DESC_CONTO0 AS Account_Description,
D.FW_ACC FW_ACCOUNT,
C2.DESC_CONTO0 AS FW_Account_Description,
D.BAL_TYPE BALANCE_TYPE_COD,
E.DESC0 BAL_TYPE_DESC,
D.CATEGORY CATEGORY,
D.CURRENCY1 CURRENCY,
D.AMOUNT1 AMOUNT,
D.ENTITY ENTITY_HOLDING,
B.DESC_AZIENDA0 ENTITY_HOLDING_DESC,
D.SCALE SCALE,
D.TEXT_ORIGIN,
D.SOURCE_ORIGIN,
D.SEGMENT_CTP
FROM ${DATASETPARTITION("003","000069",PROCESS($Scenario.code,$Period.code).code,$Scenario.code,$Period.code)} D
JOIN ED_CO_00010 A ON A.COD=D.ANL_ENTITY
JOIN AZIENDA B ON B.COD_AZIENDA = D.ENTITY
JOIN CONTO C ON C.COD_CONTO = D.ACCOUNT
JOIN CONTO C2 ON C2.COD_CONTO = D.FW_ACC
JOIN ED_CO_00002 E ON E.COD=D.BAL_TYPE
WHERE 
D.SCENARIO=${$Scenario.code}
AND D.PERIOD= ${$Period.code}
AND D.SCEN_TYPE=${$ANL_CO_00007.code}
AND D.ANL_ENTITY=${$ANL_CO_00010.code}
AND D.ACCOUNT=${$ACCOUNT.CODE}
AND D.BAL_TYPE=${$ANL_CO_00002.code}
AND D.CATEGORY=${$Category.code}


