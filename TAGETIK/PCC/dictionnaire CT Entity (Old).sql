SELECT
	R.COD_AZIENDA_GERARCHIA AS COD,
	R.DESC_AZIENDA_ELEGER0  AS DESC,
	N.COD_AZIENDA_ELEGER    AS COD_ELEGER,
	N.DESC_AZIENDA_ELEGER0  AS DESC_ELEGER
FROM
	(
		SELECT
			COD_AZIENDA_GERARCHIA,
			DESC_AZIENDA_ELEGER0
		FROM
			AZIENDA_GERARCHIA
		WHERE
			TIPO_AZIENDA_ELEGER = 'R'
	) R
	JOIN (
		SELECT
			COD_AZIENDA_GERARCHIA,
			COD_AZIENDA_GERARCHIA||'|'||COD_AZIENDA_ELEGER AS COD_AZIENDA_ELEGER,
			DESC_AZIENDA_ELEGER0
		FROM
			AZIENDA_GERARCHIA
		WHERE
			TIPO_AZIENDA_ELEGER <> 'R'
	) N ON N.COD_AZIENDA_GERARCHIA = R.COD_AZIENDA_GERARCHIA