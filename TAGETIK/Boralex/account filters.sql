--- V_CONTO_FLAT view 
CREATE VIEW V_CONTO_FLAT AS

WITH CONTO_FLAT AS (

    SELECT
	    COD_CONTO_GERARCHIA,
        COD_CONTO,
        COD_CONTO_ELEGER
    FROM CONTO_GERARCHIA_ABBI

    UNION ALL

    SELECT
	    CF.COD_CONTO_GERARCHIA,
        CF.COD_CONTO,
        CG.COD_CONTO_ELEGER_PADRE AS COD_CONTO_ELEGER
    FROM CONTO_GERARCHIA AS CG
    INNER JOIN CONTO_FLAT AS CF
        ON CG.COD_CONTO_GERARCHIA = CF.COD_CONTO_GERARCHIA
		AND CG.COD_CONTO_ELEGER = CF.COD_CONTO_ELEGER
       AND CG.TIPO_CONTO_ELEGER = 'N'
)
SELECT
    COD_CONTO_GERARCHIA,
    COD_CONTO,
    COD_CONTO_ELEGER
FROM CONTO_FLAT


---- V_AZIENDA_FLAT

CREATE VIEW V_AZIENDA_FLAT AS

WITH AZIENDA_FLAT AS (

    SELECT
	    COD_AZIENDA_GERARCHIA,
        COD_AZIENDA,
        COD_AZIENDA_ELEGER
    FROM AZIENDA_GERARCHIA_ABBI

    UNION ALL

    SELECT
	    AF.COD_AZIENDA_GERARCHIA,
        AF.COD_AZIENDA,
        AG.COD_AZIENDA_ELEGER_PADRE AS COD_AZIENDA_ELEGER
    FROM AZIENDA_GERARCHIA AS AG
    INNER JOIN AZIENDA_FLAT AS AF
        ON AG.COD_AZIENDA_GERARCHIA = AF.COD_AZIENDA_GERARCHIA
		AND AG.COD_AZIENDA_ELEGER = AF.COD_AZIENDA_ELEGER
       AND AG.TIPO_AZIENDA_ELEGER = 'N'
)
SELECT
    COD_AZIENDA_GERARCHIA,
    COD_AZIENDA,
    COD_AZIENDA_ELEGER
FROM AZIENDA_FLAT