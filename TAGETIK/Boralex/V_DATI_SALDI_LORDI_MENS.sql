CREATE VIEW V_DATI_SALDI_LORDI_MENS AS

SELECT
 COD_SCENARIO,
 RIGHT('0' + CAST(COD_PERIODO AS VARCHAR), 2) AS COD_PERIODO,
  COD_AZIENDA,
  COD_CONTO,
  COD_DEST1,
  COD_DEST2,
  COD_DEST3,
  COD_DEST4,
  COD_DEST5,
  COD_CATEGORIA,
  COD_VALUTA,
  SUM(IMPORTO) AS IMPORTO,
  COD_VALUTA_ORIGINARIA,
  SUM(IMPORTO_VALUTA_ORIGINARIA) AS IMPORTO2,
  PROVENIENZA 
FROM (
 SELECT
  COD_SCENARIO,
  CAST(COD_PERIODO AS INTEGER) AS COD_PERIODO,
  COD_AZIENDA,
  COD_CONTO,
  COD_DEST1,
  COD_DEST2,
  COD_DEST3,
  COD_DEST4,
  COD_DEST5,
  COD_CATEGORIA,
  COD_VALUTA,
  IMPORTO,
  COD_VALUTA_ORIGINARIA,
  IMPORTO_VALUTA_ORIGINARIA,
  PROVENIENZA 
 FROM DATI_SALDI_LORDI 
 
 UNION ALL
 
 SELECT
  COD_SCENARIO,
  CAST(COD_PERIODO AS INTEGER)+1 AS COD_PERIODO,
  COD_AZIENDA,
  COD_CONTO,
  COD_DEST1,
  COD_DEST2,
  COD_DEST3,
  COD_DEST4,
  COD_DEST5,
  COD_CATEGORIA,
  COD_VALUTA,
  -IMPORTO,
  COD_VALUTA_ORIGINARIA,
  -IMPORTO_VALUTA_ORIGINARIA,
  PROVENIENZA 
 FROM DATI_SALDI_LORDI 
 WHERE COD_PERIODO < 12
 AND COD_CONTO IN (
	SELECT COD_CONTO
	FROM CONTO
	WHERE NATURA_CONTO IN ('E','A')
 )
) DM 
WHERE 1=1 
GROUP BY COD_SCENARIO,
  RIGHT('0' + CAST(COD_PERIODO AS VARCHAR), 2),
  COD_AZIENDA,
  COD_CONTO,
  COD_DEST1,
  COD_DEST2,
  COD_DEST3,
  COD_DEST4,
  COD_DEST5,
  COD_CATEGORIA,
  COD_VALUTA,
  COD_VALUTA_ORIGINARIA,
  PROVENIENZA
 