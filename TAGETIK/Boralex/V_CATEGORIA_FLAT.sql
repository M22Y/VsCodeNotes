/*CATEGORIA E' LA LABEL DELLA DIMENSIONE ANALITICA 
SE NECESSARIO CREARE LA FLAT AD ESEMPIO SU UNA DIMENSIONE ANALITICA CON LABEL SKU BASTA SOSTITUIRE 'CATEGORIA' CON 'SKU'
*/
 
CREATE OR ALTER VIEW V_CATEGORIA_FLAT AS 
SELECT FLAT.COD_CATEGORIA_GERARCHIA,
L0, L1, L2, L3, L4, L5, L6, P.COD_CATEGORIA
FROM
(
SELECT L0.COD_CATEGORIA_GERARCHIA, 
L0.COD_CATEGORIA_ELEGER L0, 
L1.COD_CATEGORIA_ELEGER L1, 
L2.COD_CATEGORIA_ELEGER L2, 
L3.COD_CATEGORIA_ELEGER L3, 
L4.COD_CATEGORIA_ELEGER L4, 
L5.COD_CATEGORIA_ELEGER L5, 
L6.COD_CATEGORIA_ELEGER L6
FROM (
	SELECT COD_CATEGORIA_GERARCHIA, COD_CATEGORIA_ELEGER, COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	UNION ALL
	SELECT DISTINCT COD_CATEGORIA_GERARCHIA, NULL, COD_CATEGORIA_ELEGER COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	) L0
LEFT JOIN (
	SELECT COD_CATEGORIA_GERARCHIA, COD_CATEGORIA_ELEGER, COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	UNION ALL
	SELECT DISTINCT COD_CATEGORIA_GERARCHIA, NULL, COD_CATEGORIA_ELEGER COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	) L1
	ON L0.COD_CATEGORIA_GERARCHIA = L1.COD_CATEGORIA_GERARCHIA
		AND L0.COD_CATEGORIA_ELEGER = L1.COD_CATEGORIA_ELEGER_PADRE 
LEFT JOIN (
	SELECT COD_CATEGORIA_GERARCHIA, COD_CATEGORIA_ELEGER, COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	UNION ALL
	SELECT DISTINCT COD_CATEGORIA_GERARCHIA, NULL, COD_CATEGORIA_ELEGER COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	) L2
	ON L1.COD_CATEGORIA_GERARCHIA = L2.COD_CATEGORIA_GERARCHIA
		AND L1.COD_CATEGORIA_ELEGER = L2.COD_CATEGORIA_ELEGER_PADRE 
LEFT JOIN (
	SELECT COD_CATEGORIA_GERARCHIA, COD_CATEGORIA_ELEGER, COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	UNION ALL
	SELECT DISTINCT COD_CATEGORIA_GERARCHIA, NULL, COD_CATEGORIA_ELEGER COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	) L3
	ON L2.COD_CATEGORIA_GERARCHIA = L3.COD_CATEGORIA_GERARCHIA
		AND L2.COD_CATEGORIA_ELEGER = L3.COD_CATEGORIA_ELEGER_PADRE 
LEFT JOIN (
	SELECT COD_CATEGORIA_GERARCHIA, COD_CATEGORIA_ELEGER, COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	UNION ALL
	SELECT DISTINCT COD_CATEGORIA_GERARCHIA, NULL, COD_CATEGORIA_ELEGER COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	) L4
	ON L3.COD_CATEGORIA_GERARCHIA = L4.COD_CATEGORIA_GERARCHIA
		AND L3.COD_CATEGORIA_ELEGER = L4.COD_CATEGORIA_ELEGER_PADRE 
LEFT JOIN (
	SELECT COD_CATEGORIA_GERARCHIA, COD_CATEGORIA_ELEGER, COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	UNION ALL
	SELECT DISTINCT COD_CATEGORIA_GERARCHIA, NULL, COD_CATEGORIA_ELEGER COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	) L5
	ON L4.COD_CATEGORIA_GERARCHIA = L5.COD_CATEGORIA_GERARCHIA
		AND L4.COD_CATEGORIA_ELEGER = L5.COD_CATEGORIA_ELEGER_PADRE 
LEFT JOIN (
	SELECT COD_CATEGORIA_GERARCHIA, COD_CATEGORIA_ELEGER, COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	UNION ALL
	SELECT DISTINCT COD_CATEGORIA_GERARCHIA, NULL, COD_CATEGORIA_ELEGER COD_CATEGORIA_ELEGER_PADRE
	FROM CATEGORIA_GERARCHIA
	) L6
	ON L5.COD_CATEGORIA_GERARCHIA = L6.COD_CATEGORIA_GERARCHIA
		AND L5.COD_CATEGORIA_ELEGER = L6.COD_CATEGORIA_ELEGER_PADRE 
WHERE L0.COD_CATEGORIA_ELEGER_PADRE IS NULL
) FLAT
JOIN CATEGORIA_GERARCHIA_ABBIM P
  ON P.COD_CATEGORIA_GERARCHIA = FLAT.COD_CATEGORIA_GERARCHIA
   AND 
   (
	(P.COD_CATEGORIA_ELEGER = FLAT.L0 AND FLAT.L1 IS NULL)
	OR
	(P.COD_CATEGORIA_ELEGER = FLAT.L1 AND FLAT.L2 IS NULL)
	OR
	(P.COD_CATEGORIA_ELEGER = FLAT.L2 AND FLAT.L3 IS NULL)
	OR
	(P.COD_CATEGORIA_ELEGER = FLAT.L3 AND FLAT.L4 IS NULL)
	OR
	(P.COD_CATEGORIA_ELEGER = FLAT.L4 AND FLAT.L5 IS NULL)
	OR
	(P.COD_CATEGORIA_ELEGER = FLAT.L5 AND FLAT.L6 IS NULL)
	OR
	P.COD_CATEGORIA_ELEGER = FLAT.L6
	)
 
WHERE FLAT.COD_CATEGORIA_GERARCHIA = '$' /*CODICE GERARCHIA DA CAMBIARE */