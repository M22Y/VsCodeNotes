WITH src AS (
    SELECT
        DSL.COD_SCENARIO AS SCENARIO,
        DSL.COD_PERIODO  AS PERIOD,
        DSL.COD_AZIENDA  AS ENTITY,
        DSL.COD_CONTO    AS ACCOUNT,
        '$AMOUNT'        AS CATEGORY,
        DSL.COD_VALUTA   AS CURRENCY,
        DSL.COD_DEST1    AS SITE,
        DSL.COD_DEST2    AS LIGNE_AFFAIRE,
        DSL.COD_DEST3    AS DEPARTMENT,
        DSL.COD_DEST4    AS MODELE_AFFAIRE,
        SUM(DSL.IMPORTO) AS AMOUNT_REFA
    FROM V_DATI_SALDI_FULL_MENSILI AS DSL
    JOIN SCENARIO_PERIODO SP
      ON SP.COD_SCENARIO = ${$Scenario.ref1.code}
     AND DSL.COD_PERIODO = SP.COD_PERIODO
     AND SP.FLAG_BLOCCATO = 1
    WHERE DSL.COD_SCENARIO = ${$Scenario.ref1.code}
      AND DSL.COD_CONTO LIKE '%_GEN'
      AND (
            DSL.COD_CATEGORIA IN (
                SELECT DISTINCT C.COD_CATEGORIA
                FROM CATEGORIA_GERARCHIA_ABBIM AS C
                WHERE C.COD_CATEGORIA_ELEGER = 'PLAN_FW'
            )
            OR DSL.COD_CATEGORIA = '$AMOUNT'
      )
      AND DSL.IMPORTO <> 0
    GROUP BY
        DSL.COD_SCENARIO,
        DSL.COD_PERIODO,
        DSL.COD_AZIENDA,
        DSL.COD_CONTO,
        DSL.COD_VALUTA,
        DSL.COD_DEST1,
        DSL.COD_DEST2,
        DSL.COD_DEST3,
        DSL.COD_DEST4
)

UPDATE &TARGET_DATASET&  T
SET
    AMOUNT_P01 = CASE WHEN SRC.PERIOD = '01' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P01 END,
    AMOUNT_P02 = CASE WHEN SRC.PERIOD = '02' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P02 END,
    AMOUNT_P03 = CASE WHEN SRC.PERIOD = '03' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P03 END,
    AMOUNT_P04 = CASE WHEN SRC.PERIOD = '04' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P04 END,
    AMOUNT_P05 = CASE WHEN SRC.PERIOD = '05' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P05 END,
    AMOUNT_P06 = CASE WHEN SRC.PERIOD = '06' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P06 END,
    AMOUNT_P07 = CASE WHEN SRC.PERIOD = '07' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P07 END,
    AMOUNT_P08 = CASE WHEN SRC.PERIOD = '08' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P08 END,
    AMOUNT_P09 = CASE WHEN SRC.PERIOD = '09' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P09 END,
    AMOUNT_P10 = CASE WHEN SRC.PERIOD = '10' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P10 END,
    AMOUNT_P11 = CASE WHEN SRC.PERIOD = '11' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P11 END,
    AMOUNT_P12 = CASE WHEN SRC.PERIOD = '12' THEN SRC.AMOUNT_REFA ELSE T.AMOUNT_P12 END,
    (AMOUN_P01+ etc.) AS AMOUNT,
FROM src AS SRC
WHERE T.ENTITY   = SRC.ENTITY
  AND T.ACCOUNT  = SRC.ACCOUNT
  AND T.CATEGORY = SRC.CATEGORY
  AND T.CD1      = SRC.SITE
  AND T.CD2      = SRC.LIGNE_AFFAIRE
  AND T.CURRENCY = SRC.CURRENCY
  -- Filters for the target update.
  AND T.SCENARIO = ${$Scenario.code}
  AND T.ENTITY   = ${$Entity.code}
  AND T.ACCOUNT LIKE '%_GEN'
  AND T.TEXT_ORIGIN = '000010'
  AND T.CATEGORY = '$AMOUNT'