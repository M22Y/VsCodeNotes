SELECT
    DSL.COD_SCENARIO AS SCENARIO,
    DSL.COD_PERIODO  AS PERIOD,
    DSL.COD_AZIENDA  AS ENTITY,
    DSL.COD_CONTO    AS ACCOUNT,
    DSL.COD_CATEGORIA AS CATEGORY,
    DSL.COD_VALUTA AS CURRENCY,
	DSL.COD_DEST1    AS SITE,
	DSL.COD_DEST2    AS LIGNE_AFFAIRE,
	DSL.COD_DEST3    AS DEPARTMENT,
    DSL.COD_DEST4    AS MODELE_AFFAIRE,
    SUM(DSL.IMPORTO) AS AMOUNT_REFA


FROM V_DATI_SALDI_FULL_MENSILI as DSL
	JOIN SCENARIO_PERIODO SP 
		ON SP.COD_SCENARIO=@P0050@
		AND DSL.COD_PERIODO=SP.COD_PERIODO 
		AND SP.FLAG_BLOCCATO=1
WHERE DSL.COD_SCENARIO = @P0050@ 
AND DSL.COD_CONTO IN (@P0100@)
AND (dsl.COD_CATEGORIA IN (SELECT DISTINCT C.COD_CATEGORIA FROM CATEGORIA_GERARCHIA_ABBIM AS C WHERE C.COD_CATEGORIA_ELEGER='PLAN_FW') OR DSL.COD_CATEGORIA='$AMOUNT') 
AND DSL.IMPORTO<>0

GROUP BY 
    DSL.COD_SCENARIO, 
    DSL.COD_PERIODO, 
    DSL.COD_AZIENDA, 
    DSL.COD_CONTO, 
    DSL.COD_CATEGORIA, 
    DSL.COD_VALUTA,
    DSL.COD_DEST1,
	DSL.COD_DEST2,
	DSL.COD_DEST3,
	DSL.COD_DEST4