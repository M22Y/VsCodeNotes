/*OE_EBUCC combinations*/

DROP TABLE IF EXISTS #OE_EBUCC

SELECT ACC.ACCOUNT, ENT.ENTITY, CC.COST_CENTER, BU.BUSINESS_UNIT
INTO #OE_EBUCC
FROM 
(
SELECT COD_CONTO AS ACCOUNT 
FROM CONTO_GERARCHIA_ABBI 
WHERE COD_CONTO_GERARCHIA='H003'
AND COD_CONTO_ELEGER = 'OE_EBUCC'
AND COD_CONTO_ELEGER  IN ('OE_E','OE_EBU','OE_EBUCC')
) ACC
CROSS JOIN 
( SELECT COD_AZIENDA  AS ENTITY
FROM AZIENDA 
WHERE COD_AZIENDA NOT LIKE '$%') ENT
CROSS JOIN 
(SELECT COD_DEST1 AS COST_CENTER
FROM DEST1
WHERE COD_DEST1<>'NA') CC
CROSS JOIN 
(SELECT COD_DEST2 AS BUSINESS_UNIT
FROM DEST2
WHERE COD_DEST2<>'NA') BU


