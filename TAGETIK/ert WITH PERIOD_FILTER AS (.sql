WITH PERIOD_FILTER AS (
	SELECT COD_PERIODO
	FROM SCENARIO_PERIODO
	WHERE COD_RACCOLTA='#PROCESS#' AND FLAG_BLOCCATO=0
	AND COD_SCENARIO=(SELECT COD_SCENARIO FROM SCENARIO_PERIODO WHERE COD_RACCOLTA ='#PROCESS#' ORDER BY COD_SCENARIO LIMIT 1)
),
CombinedTables AS (  
	SELECT SCENARIO,PERIOD,ACCOUNT,ENTITY,CATEGORY,DIVISION,CUSTOMER,PRODUCT,RSRCE,OPE_TYPE,TEXT_ORIGIN,AMOUNT 
	FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute5.code,"01").code, $Scenario.attribute5.code, ,,,"(SELECT NULL AS SCENARIO, NULL AS PERIOD,NULL AS ACCOUNT, NULL AS ENTITY, NULL AS CATEGORY, NULL AS DIVISION, NULL AS CUSTOMER, NULL AS PRODUCT, NULL AS RSRCE, NULL AS OPE_TYPE, NULL AS TEXT_ORIGIN, 0 AS AMOUNT)")} AS T1
	
),
MONTHLY AS (
	SELECT 
		SCENARIO,
		PERIOD,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        /*OPE_TYPE,*/
		TEXT_ORIGIN,
		SUM(AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables
	WHERE 
		PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		AND ACCOUNT = 'RV_REVENUES'
		AND SCENARIO IN  (SELECT ATTRIBUTO5 FROM SCENARIO WHERE COD_SCENARIO= '#SCENARIOS#' LIMIT 1)
	GROUP BY 
		SCENARIO,
		PERIOD,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        /*OPE_TYPE,*/
		TEXT_ORIGIN     
	HAVING 
		SUM(AMOUNT)<>0
),
TOT AS (
	SELECT 
		SCENARIO,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        /*OPE_TYPE,*/
		TEXT_ORIGIN,
		SUM(AMOUNT) AS M_TOT
	FROM 
		CombinedTables
	WHERE 
		PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		AND ACCOUNT = 'RV_REVENUES'
		AND SCENARIO IN  (SELECT ATTRIBUTO5 FROM SCENARIO WHERE COD_SCENARIO= '#SCENARIOS#' LIMIT 1)
	GROUP BY 
		SCENARIO,
		ACCOUNT,
		ENTITY,
		CATEGORY,
		DIVISION,
		CUSTOMER,
		PRODUCT,
		RSRCE,
        /*OPE_TYPE,*/
		TEXT_ORIGIN   
	HAVING 
		SUM(AMOUNT)<>0
)
SELECT  
	'#SCENARIOS#' AS SCENARIO, 
	MONTHLY.SCENARIO AS HIST_SCENARIO,
	MONTHLY.PERIOD,
	MONTHLY.ACCOUNT,
	MONTHLY.ENTITY,
	MONTHLY.CATEGORY,
	MONTHLY.DIVISION,
	MONTHLY.CUSTOMER,
	MONTHLY.PRODUCT,
	MONTHLY.RSRCE,
    /*MONTHLY.OPE_TYPE,*/
	MONTHLY.TEXT_ORIGIN,
	SUM(MONTHLY.M_AMOUNT / TOT.M_TOT) AS PERC_DRIVER
FROM
	MONTHLY
LEFT JOIN 
	TOT
ON 
	MONTHLY.SCENARIO = TOT.SCENARIO
	AND MONTHLY.ACCOUNT = TOT.ACCOUNT
	AND MONTHLY.ENTITY = TOT.ENTITY
	AND MONTHLY.CATEGORY = TOT.CATEGORY
	AND MONTHLY.DIVISION = TOT.DIVISION
	AND MONTHLY.CUSTOMER = TOT.CUSTOMER
	AND MONTHLY.PRODUCT = TOT.PRODUCT
	AND MONTHLY.RSRCE = TOT.RSRCE
    /*AND MONTHLY.OPE_TYPE = TOT.OPE_TYPE*/


WHERE 
	MONTHLY.SCENARIO IN  (SELECT ATTRIBUTO5 FROM SCENARIO WHERE COD_SCENARIO= '#SCENARIOS#' LIMIT 1)
	AND MONTHLY.ACCOUNT = 'RV_REVENUES'
	AND MONTHLY.CATEGORY = 'RV_AMOUNT'
GROUP BY 
	MONTHLY.SCENARIO,
	MONTHLY.PERIOD,
	MONTHLY.ACCOUNT,
	MONTHLY.ENTITY,
	MONTHLY.CATEGORY,
	MONTHLY.DIVISION,
	MONTHLY.CUSTOMER,
	MONTHLY.PRODUCT,
	MONTHLY.RSRCE,
    /*MONTHLY.OPE_TYPE,*/
	MONTHLY.TEXT_ORIGIN

