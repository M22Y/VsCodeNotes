WITH PERIOD_FILTER AS (
	SELECT COD_PERIODO
	FROM SCENARIO_PERIODO
	WHERE COD_RACCOLTA='#PROCESS#' AND FLAG_BLOCCATO=0
	AND COD_SCENARIO=(SELECT COD_SCENARIO FROM SCENARIO_PERIODO WHERE COD_RACCOLTA ='#PROCESS#' ORDER BY COD_SCENARIO LIMIT 1)
),
CombinedTables AS (  
	SELECT SCENARIO,PERIOD,ACCOUNT,ENTITY,CATEGORY,DIVISION,CUSTOMER,PRODUCT,RSRCE,OPE_TYPE,TEXT_ORIGIN,AMOUNT 
	FROM ${DATASETPARTITION("004", "000003", PROCESS($Scenario.attribute6.code,"01").code, $Scenario.attribute6.code, "01",,,"(SELECT NULL AS SCENARIO, NULL AS PERIOD,NULL AS ACCOUNT, NULL AS ENTITY, NULL AS CATEGORY, NULL AS DIVISION, NULL AS CUSTOMER, NULL AS PRODUCT, NULL AS RSRCE, NULL AS OPE_TYPE, NULL AS TEXT_ORIGIN, 0 AS AMOUNT)")} AS T1

),
DENOMINATOR AS (
	SELECT 
		CT.SCENARIO,
		CT.ACCOUNT,
		CT.ENTITY,
		CT.CATEGORY,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT,
		SUM(CT.AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables AS CT
	WHERE 
		CT.PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		        AND CT.ACCOUNT = 'RV_REVENUES'
		AND CT.SCENARIO IN  (SELECT ATTRIBUTO6 FROM SCENARIO WHERE COD_SCENARIO= '#SCENARIOS#' LIMIT 1)
        AND CT.RSRCE IN (SELECT COD FROM  ED_RESOURCE_GERARCHIA_FLAT WHERE COD_GERARCHIA='999' AND COD_ELEGER7 like '%STV_TLG%')
	GROUP BY 
		CT.SCENARIO,
		CT.ACCOUNT,
		CT.ENTITY,
		CT.CATEGORY,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT
	HAVING 
		SUM(CT.AMOUNT)<>0
),
NUMERATOR AS (
	SELECT 
		CT.SCENARIO,
		CT.ACCOUNT,
		CT.ENTITY,
		CT.CATEGORY,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT,
		CT.RSRCE,
		SUM(CT.AMOUNT) AS M_AMOUNT
	FROM 
		CombinedTables AS CT
	WHERE 
		CT.PERIOD IN (SELECT COD_PERIODO FROM PERIOD_FILTER)
		        AND CT.ACCOUNT = 'RV_REVENUES'
		AND CT.SCENARIO IN  (SELECT ATTRIBUTO6 FROM SCENARIO WHERE COD_SCENARIO= '#SCENARIOS#' LIMIT 1)
        AND CT.RSRCE NOT IN (SELECT COD FROM  ED_RESOURCE_GERARCHIA_FLAT WHERE COD_GERARCHIA='999' AND COD_ELEGER7 like '%STV_TLG%')
	GROUP BY 
		CT.SCENARIO,
		CT.ACCOUNT,
		CT.ENTITY,
		CT.CATEGORY,
		CT.DIVISION,
		CT.CUSTOMER,
		CT.PRODUCT,
		CT.RSRCE
	HAVING 
		SUM(CT.AMOUNT)<>0
)
SELECT  
	'#SCENARIOS#' AS SCENARIO, 
	NUMERATOR.SCENARIO AS HIST_SCENARIO,
	NUMERATOR.ACCOUNT,
	NUMERATOR.ENTITY,
	NUMERATOR.CATEGORY,
	NUMERATOR.DIVISION,
	NUMERATOR.CUSTOMER,
	NUMERATOR.PRODUCT,
	NUMERATOR.RSRCE,
	SUM(NUMERATOR.M_AMOUNT / DENOMINATOR.M_AMOUNT) AS VALUE_PERCENTAGE
FROM
	NUMERATOR
LEFT JOIN 
	DENOMINATOR
ON 
	NUMERATOR.SCENARIO = DENOMINATOR.SCENARIO
	AND NUMERATOR.ACCOUNT = DENOMINATOR.ACCOUNT
	AND NUMERATOR.ENTITY = DENOMINATOR.ENTITY
	AND NUMERATOR.CATEGORY = DENOMINATOR.CATEGORY
	AND NUMERATOR.DIVISION = DENOMINATOR.DIVISION
	AND NUMERATOR.CUSTOMER = DENOMINATOR.CUSTOMER
	AND NUMERATOR.PRODUCT = DENOMINATOR.PRODUCT

WHERE 
	NUMERATOR.SCENARIO IN  (SELECT ATTRIBUTO6 FROM SCENARIO WHERE COD_SCENARIO= '#SCENARIOS#' LIMIT 1)
	AND NUMERATOR.CATEGORY = 'RV_AMOUNT'
GROUP BY 
	NUMERATOR.SCENARIO,
	NUMERATOR.ACCOUNT,
	NUMERATOR.ENTITY,
	NUMERATOR.CATEGORY,
	NUMERATOR.DIVISION,
	NUMERATOR.CUSTOMER,
	NUMERATOR.PRODUCT,
	NUMERATOR.RSRCE
HAVING 
	SUM(NUMERATOR.M_AMOUNT / DENOMINATOR.M_AMOUNT)<>0

