SELECT A.COD,
    C.DESC0,
    C.DESC1,
    A.COD_ELEGER,
    B.DESC_ELEGER0,
    B.DESC_ELEGER1
FROM ED_TECH_ACCTS_GERARCHIA_ABBI A
    JOIN ED_TECH_ACCTS_GERARCHIA B ON A.COD_ELEGER = B.COD_ELEGER
    JOIN ED_TECH_ACCTS C ON A.COD = C.COD
WHERE A.COD_GERARCHIA = '100'












