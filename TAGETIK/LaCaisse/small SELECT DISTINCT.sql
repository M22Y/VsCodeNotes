SELECT DISTINCT
    SCENARIO AS SCENARIO_HISTO,
    ENTITY,
    DIVISION,
    CUSTOMER,
    PRODUCT
FROM ${DATASETPARTITION("006", "000004", PROCESS($Scenario.attribute5.code,"01").code, $Scenario.attribute5.code,,,,"(SELECT NULL AS SCENARIO, NULL AS PERIOD, NULL AS ACCOUNT, NULL AS ENTITY, NULL AS CATEGORY, NULL AS DIVISION, NULL AS CUSTOMER, NULL AS PRODUCT, 0 AS VALUE_DOLLARS, NULL AS TEXT_ORIGIN)")} AS T1
WHERE 
    SCENARIO IN (${$Scenario.attribute5.code})
    AND VALUE_DOLLARS <> 0