MERGE INTO &REP&
USING ( 
	SELECT SCENARIO, ENTITY, ACCOUNT, COST_CENTER, FOURNISSEUR, PROJECT, SNA, T_ENTITY, T_ACCOUNT, T_COST_CENTER, T_FOURNISSEUR, T_PROJECT, T_SNA, TRANSFER_TYPE, CURRENCY, MAX(NOTES) AS M_NOTES, MAX(NUM_ECR) AS M_NUM_ECR
	FROM &REP& K
	WHERE K.TEXT_ORIGIN='000200' AND K.SCENARIO='#SCENARIOS#'
	GROUP BY SCENARIO,ENTITY, ACCOUNT, COST_CENTER, FOURNISSEUR, PROJECT, SNA, T_ENTITY, T_ACCOUNT, T_COST_CENTER, T_FOURNISSEUR, T_PROJECT, T_SNA, TRANSFER_TYPE, CURRENCY
	) A
ON  &REP&.TEXT_ORIGIN IN ('000210', '000240')
	AND &REP&.ENTITY=A.ENTITY
	AND &REP&.ACCOUNT=A.ACCOUNT
	AND &REP&.COST_CENTER=A.COST_CENTER
	AND &REP&.T_ENTITY=A.T_ENTITY
	AND &REP&.T_ACCOUNT=A.T_ACCOUNT
	AND &REP&.T_COST_CENTER=A.T_COST_CENTER
	AND &REP&.T_FOURNISSEUR=A.T_FOURNISSEUR
	AND &REP&.T_PROJECT=A.T_PROJECT
	AND &REP&.T_SNA=A.T_SNA
	AND &REP&.FOURNISSEUR=A.FOURNISSEUR
	AND &REP&.PROJECT=A.PROJECT
	AND &REP&.SNA=A.SNA
	AND &REP&.TRANSFER_TYPE=A.TRANSFER_TYPE
	AND &REP&.CURRENCY=A.CURRENCY
WHEN MATCHED THEN UPDATE SET &REP&.NOTES=A.M_NOTES,
&REP&.NUM_ECR=A.M_NUM_ECR;