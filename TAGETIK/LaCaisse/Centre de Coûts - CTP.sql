
-- old SRC

SELECT A.COD_DEST2 AS CODE, B.DESC_DEST20 AS DESCRIPTION
FROM    DEST2_GERARCHIA_ABBI A
JOIN    DEST2 B ON A.COD_DEST2 = B.COD_DEST2
WHERE   A.COD_DEST2_GERARCHIA ='10'
AND     A.COD_DEST2_ELEGER NOT IN ('0103')
AND     B.DATA_FINE IS NULL
ORDER BY A.COD_DEST2 ASC;



