(
SELECT  COD_DEST2 AS COD,
        DESC_DEST20 AS DESC0 ,
        COD_AZIENDA AS COD_ENTITY,
        DESC_AZIENDA0 AS DESC_ENTITY
FROM DEST2_GERARCHIA_FLAT
JOIN AZIENDA ON COD_AZIENDA=COD_DEST2_ELEGER7
WHERE COD_AZIENDA='E100'
UNION
SELECT COD, DESC0,  COD_ENTITY, DESC_ENTITY 
FROM (VALUES ('%', '%', '%', '%')) 
AS T (COD, DESC0, COD_ENTITY, DESC_ENTITY )  
UNION
SELECT  COD_DEST2 AS COD,
        DESC_DEST20 AS DESC0 ,  
        '%' AS COD_ENTITY, 
        '%' AS DESC_ENTITY
FROM DEST2_GERARCHIA_FLAT
UNION
SELECT  '%' AS COD ,
        '%' AS DESC0,  
        COD_AZIENDA AS COD_ENTITY,
        DESC_AZIENDA0 AS DESC_ENTITY
FROM AZIENDA
WHERE COD_AZIENDA NOT IN ('$') AND COD_AZIENDA='E100'
)

ORDER BY COD_ENTITY ASC, COD ASC
